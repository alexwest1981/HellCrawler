def data_keys() -> dict[str, str]:
    """Nycklar ur spelets eget data: en källa, så filerna inte kan glida ifrån spelet."""
    ut: dict[str, str] = {}
    kort: dict[str, str] = {}          ## id -> kortets namn, för kamraternas (samma id)
    for f in sorted(glob.glob(str(GAME / "data" / "cards" / "*.json"))):
        for c in json.loads(Path(f).read_text()):
            kort[str(c["id"])] = str(c.get("name", c["id"]))
            ut["card.%s" % c["id"]] = c.get("name", c["id"])
    for f in sorted(glob.glob(str(GAME / "data" / "enemies" / "*.json"))):
        for e in json.loads(Path(f).read_text()):
            ut["enemy.%s" % e["id"]] = e.get("name", e["id"])
    for f in sorted(glob.glob(str(GAME / "data" / "stages" / "*.json"))):
        d = json.loads(Path(f).read_text())
        ut["stage.%s" % d["id"]] = d.get("name", d["id"])
    for p in json.loads((GAME / "data" / "powerups.json").read_text()):
        ut["powerup.%s" % p["id"]] = p.get("name", p["id"])
        ut["powerup.%s.desc" % p["id"]] = p.get("text", "")
    # Smedens träd: noderna står på svenska i datat (det är källspråket), så de behöver nycklar
    # precis som korten. Grenen bär sitt namn som nyckel — smeden skriver ut det i titeln, och en
    # ny gren får därför ett värde att översätta utan att någon kod ändras.
    for n in json.loads((GAME / "data" / "tree.json").read_text()):
        nid = str(n["id"])
        ut["tree.%s" % nid] = n.get("name", nid)
        ut["tree.%s.text" % nid] = n.get("text", "")
        gren = str(n.get("branch", ""))
        if gren:
            ut["tree.branch.%s" % gren.lower()] = gren
    # Kamraterna: samma id som deras kort i data/cards, för det är så de hamnar i leken. Namnet
    # hämtas ur kortet (crawlers-filen har inget namn), raden ur kamratens egen "text".
    for f in sorted(glob.glob(str(GAME / "data" / "crawlers" / "*.json"))):
        for c in json.loads(Path(f).read_text()):
            cid = str(c["id"])
            ut["crawler.%s" % cid] = kort.get(cid, cid)
            ut["crawler.%s.text" % cid] = c.get("text", "")
    return ut


def build(code: str) -> dict:
    ut = dict(UI.get(code, {}))
    # Skärmarnas nycklar (UI_SKARMAR) läggs i SAMMA tabell som HUD:ens: de är samma sorts text, och
    # Tr.is_complete kräver ett eget värde för var och en av dem på varje språk.
    ut.update(UI_SKARMAR.get(code, {}))
    # Menyns nycklar (M39). De ligger i sin egen tabell (tools/meny_i18n.py) men hamnar i samma fil
    # som resten: Tr.is_complete kräver ett värde även för dem, och provet i test_i18n ser det.
    ut.update(MENY.get(code, {}))
    # HUD:ens rader (M40): samma sorts text, men skriven nyckel för nyckel (se tools/meny_i18n.py).
    for nyckel, per_språk in HUD_RADER.items():
        if code in per_språk:
            ut[nyckel] = per_språk[code]
    data = data_keys()
    for k, v in data.items():
        if code == "en" and k.startswith("stage."):
            ut[k] = STAGE_EN.get(k.split(".", 1)[1], v)
        elif code == "en" and k.startswith("powerup.") and k.endswith(".desc"):
            ut[k] = POWERUP_EN_DESC.get(k.split(".")[1], v)
        elif code == "en" and k in DATA_EN:
            ut[k] = DATA_EN[k]
        elif code in ("sv", "en"):
            ut[k] = v
        elif k.startswith("crawler.") and not k.endswith(".text"):
            # Kamratens namn ÄR kortets: samma id, och den hyrda kamraten läggs i leken som just
            # det kortet. Värdet lånas ur kortets rad i stället för att skrivas en gång till per
            # språk — två rader som ska säga samma sak glider isär förr eller senare.
            ut[k] = CONTENT.get(code, {}).get("card.%s" % k.split(".", 1)[1], v)
        else:
            # NYCKELN SKRIVS ALLTID. Det stod i kommentaren längre ner, men en ny datanyckel (t.ex.
            # en ny nod i trädet) skrevs bara för sv/en och måste läggas i CONTENT-filen för de elva
            # andra — och då blev nyckeluppsättningen OLIKA mellan filerna och hela sviten föll på
            # "alla datanycklar finns i alla tretton filer". Reservvägen är ENGELSKAN, aldrig
            # svenskan: provet kräver att svenskan inte läcker in i ett annat språk, och en rad på
            # engelska är den väg Tr själv tar när en nyckel saknas.
            ut[k] = CONTENT.get(code, {}).get(k, DATA_EN.get(k, v))
    # Övriga språk: innehållsnamnen kommer ur CONTENT, så varje språk har egna namn i stället för att
    # falla tillbaka på engelskan i Tr. Nyckeln skrivs alltid — det är det som gör nyckeluppsättningen
    # identisk i alla 13 filer.
    ut.update(CONTENT.get(code, {}))
    ut["_meta.name"] = LANG_NAMES.get(code, code)
    ut["_meta.code"] = code
    # Uppgraderingarnas rad: FORMEN är översatt, SIFFRAN kommer ur effekten i data/powerups.json.
    # Så kan en rad inte säga "+2 %" medan koden ger "+10 %" — det var precis vad byns area-rad
    # gjorde innan (texten sa 2 %, Rules.damage gav area/5 = 10 %).
    for pid, mall in POWERUP_FMT.get(code, {}).items():
        ut["powerup.%s.fmt" % pid] = mall
    return ut


def write_all() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for code in UI:
        (OUT / f"{code}.json").write_text(json.dumps(build(code), ensure_ascii=False, indent=1) + "\n")
        print("  %s.json  %d nycklar" % (code, len(build(code))))
    return 0


def platshallare(s: str) -> list:
    """Formatplatshållarna i en sträng, i ordning. %% räknas som ett procenttecken, inte som en."""
    ut = []
    i = 0
    while i < len(s):
        if s[i] == "%" and i + 1 < len(s):
            if s[i + 1] == "%":
                i += 2
                continue
            m = re.match(r"%[-+0-9.]*([sdfi])", s[i:])
            if m:
                ut.append(m.group(0))
                i += m.end()
                continue
        i += 1
    return ut


def check() -> int:
    källa = json.loads((OUT / "sv.json").read_text())
    källnycklar = set(källa)
    fel = 0
    for f in sorted(glob.glob(str(OUT / "*.json"))):
        kod = Path(f).stem
        fil = json.loads(Path(f).read_text())
        nycklar = set(fil)
        extra = nycklar - källnycklar
        saknade = källnycklar - nycklar
        tomma = [k for k, v in fil.items() if str(v).strip() == ""]
        # En översättning får inte ändra antalet platshållare: då får Godot fler eller färre argument
        # än formen ber om, och felet syns bara som skräp i en rad (eller inte alls).
        avvikande = []
        for k in sorted(nycklar & källnycklar):
            if k.startswith("_meta"):
                continue
            if len(platshallare(str(fil[k]))) != len(platshallare(str(källa[k]))):
                avvikande.append("%s (%s mot %s)" % (
                    k, " ".join(platshallare(str(fil[k]))), " ".join(platshallare(str(källa[k])))))
        egna = sum(1 for k in nycklar if k in källa and str(fil[k]) != str(källa[k]))
        if extra or saknade or tomma or avvikande:
            fel += 1
            print("  %-8s FEL extra: %s  tomma: %s" % (kod, sorted(extra)[:4], tomma[:4]))
            # Skillnaden mot svenska, nyckel för nyckel: en nyckel som saknas är en tom ruta i
            # gränssnittet, och den syntes inte här innan (kontrollen såg bara påhittade nycklar).
            if saknade:
                print("           %d nycklar saknas mot svenska: %s" % (
                    len(saknade), " ".join(sorted(saknade)[:8]) + (" …" if len(saknade) > 8 else "")))
            for a in avvikande[:6]:
                print("           platshållare: %s" % a)
        else:
            print("  %-8s ok  %3d nycklar, %3d egna värden (%.0f %% översatt)" % (
                kod, len(nycklar), egna, 100.0 * egna / max(1, len(källnycklar))))
    return fel


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    return check() if args.check else write_all()


